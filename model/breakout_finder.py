def _round_price_to_tick(price: float, tick_size: float = FRVP_TICK_SIZE) -> float:
    return round(round(price / tick_size) * tick_size, 4)


def _calculate_volume_profile(
    profile_bars: list[Any],
    tick_size: float = FRVP_TICK_SIZE,
    value_area_pct: float = FRVP_VALUE_AREA_PCT,
) -> Optional[VolumeProfileContext]:
    """Approximate TradingView FRVP from 1-minute OHLCV bars.

    Because the training data is OHLCV and not tick/trade prints, volume is
    distributed evenly across each bar's high-low range. This is intentionally
    approximate, but stable enough for pattern mining and level validation.
    """
    if len(profile_bars) < FRVP_MIN_PROFILE_BARS:
        return None

    volume_by_price: dict[float, float] = {}
    total_volume = 0.0
    highs: list[float] = []
    lows: list[float] = []

    for bar in profile_bars:
        high = safe_float(getattr(bar, "high", None), None)
        low = safe_float(getattr(bar, "low", None), None)
        close = safe_float(getattr(bar, "close", None), None)
        volume = safe_float(getattr(bar, "volume", None), 0.0) or 0.0

        if high is None or low is None or volume <= 0:
            continue

        if high < low:
            high, low = low, high

        highs.append(high)
        lows.append(low)
        total_volume += volume

        start_bin = _round_price_to_tick(low, tick_size)
        end_bin = _round_price_to_tick(high, tick_size)

        price_bins: list[float] = []
        price = start_bin
        while price <= end_bin + 1e-9:
            price_bins.append(round(price, 4))
            price += tick_size

        if not price_bins and close is not None:
            price_bins = [_round_price_to_tick(close, tick_size)]

        if not price_bins:
            continue

        volume_per_bin = volume / len(price_bins)
        for price_bin in price_bins:
            volume_by_price[price_bin] = volume_by_price.get(price_bin, 0.0) + volume_per_bin

    if not volume_by_price or total_volume < FRVP_MIN_PROFILE_VOLUME or not highs or not lows:
        return None

    profile_high = max(highs)
    profile_low = min(lows)
    first_close = safe_float(getattr(profile_bars[0], "close", None), None)
    if first_close is None or first_close <= 0:
        first_close = safe_float(getattr(profile_bars[0], "open_value", None), None)

    if first_close is None or first_close <= 0:
        return None

    profile_range_pct = (profile_high - profile_low) / first_close
    if profile_range_pct < FRVP_MIN_PROFILE_RANGE_PCT:
        return None

    poc = max(volume_by_price, key=volume_by_price.get)
    sorted_prices = sorted(volume_by_price.keys())
    poc_index = sorted_prices.index(poc)

    target_volume = sum(volume_by_price.values()) * value_area_pct
    included = {poc}
    included_volume = volume_by_price[poc]
    lower_index = poc_index - 1
    upper_index = poc_index + 1

    while included_volume < target_volume and (lower_index >= 0 or upper_index < len(sorted_prices)):
        lower_volume = volume_by_price[sorted_prices[lower_index]] if lower_index >= 0 else -1
        upper_volume = volume_by_price[sorted_prices[upper_index]] if upper_index < len(sorted_prices) else -1

        if upper_volume >= lower_volume:
            price_to_add = sorted_prices[upper_index]
            upper_index += 1
        else:
            price_to_add = sorted_prices[lower_index]
            lower_index -= 1

        included.add(price_to_add)
        included_volume += volume_by_price[price_to_add]

    val = min(included)
    vah = max(included)
    fight_zone_high = _find_fight_zone_high_above_vah(
        volume_by_price=volume_by_price,
        vah=vah,
        poc_volume=volume_by_price[poc],
    )

    return VolumeProfileContext(
        profile_type="",
        start_bar=profile_bars[0],
        end_bar=profile_bars[-1],
        val=round(val, 4),
        poc=round(poc, 4),
        vah=round(vah, 4),
        fight_zone_high=round(max(vah, fight_zone_high), 4),
        profile_high=round(profile_high, 4),
        profile_low=round(profile_low, 4),
        total_volume=round(total_volume, 2),
        volume_by_price=volume_by_price,
    )


def _find_fight_zone_high_above_vah(
    volume_by_price: dict[float, float],
    vah: float,
    poc_volume: float,
) -> float:
    """Find the hidden seller-fight zone above VAH.

    A fight zone is approximated as meaningful volume above VAH. This captures
    the repeated behavior we observed where official VAH is not enough: sellers
    are still active in a nearby upper-volume shelf above VAH.
    """
    if poc_volume <= 0:
        return vah

    threshold = poc_volume * FRVP_FIGHT_ZONE_MIN_POC_BIN_SHARE
    prices_above_vah = sorted(price for price in volume_by_price if price > vah)
    if not prices_above_vah:
        return vah

    fight_high = vah
    started = False
    gap_count = 0

    for price in prices_above_vah:
        bin_volume = volume_by_price.get(price, 0.0)
        if bin_volume >= threshold:
            started = True
            gap_count = 0
            fight_high = price
        elif started:
            gap_count += 1
            # A few low-volume rows can exist inside the fight shelf because
            # the OHLCV approximation is coarse. Stop after a clear gap.
            if gap_count >= 5:
                break

    return fight_high


_VALID_MOVEMENT_PROFILE_CACHE: Optional[dict[tuple[str, str], list[dict[str, str]]]] = None


def _parse_csv_datetime(value: Any) -> Optional[datetime.datetime]:
    if value is None:
        return None
    value_str = str(value).strip()
    if not value_str:
        return None
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%d %H:%M", "%Y-%m-%dT%H:%M:%S"):
        try:
            return datetime.datetime.strptime(value_str, fmt)
        except ValueError:
            continue
    try:
        return datetime.datetime.fromisoformat(value_str)
    except Exception:
        return None


def _load_valid_movement_profile_cache() -> dict[tuple[str, str], list[dict[str, str]]]:
    """Load selected, valid movement profiles generated by the FRVP movement finder.

    The breakout finder should not guess FRVP start/end ranges anymore. It uses
    only rows from model/frvp_movement_profiles_valid.csv, where movement_is_valid
    already removed thin/choppy profiles like CAST.
    """
    global _VALID_MOVEMENT_PROFILE_CACHE
    if _VALID_MOVEMENT_PROFILE_CACHE is not None:
        return _VALID_MOVEMENT_PROFILE_CACHE

    cache: dict[tuple[str, str], list[dict[str, str]]] = {}
    profile_file = FRVP_VALID_MOVEMENT_PROFILES_FILE
    if not os.path.exists(profile_file):
        _VALID_MOVEMENT_PROFILE_CACHE = cache
        return cache

    with open(profile_file, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            symbol = str(row.get("symbol") or "").strip()
            trade_date = str(row.get("trade_date") or "").strip()
            movement_is_valid = str(row.get("movement_is_valid") or "").strip().lower()
            if not symbol or not trade_date:
                continue
            if movement_is_valid not in {"true", "1", "yes", "y"}:
                continue
            cache.setdefault((symbol, trade_date), []).append(row)

    _VALID_MOVEMENT_PROFILE_CACHE = cache
    return cache


def _make_profile_boundary_bar(
    row: dict[str, str],
    bars: list[Any],
    timestamp_key: str,
    high_key: str = "frvp_profile_high",
    low_key: str = "frvp_profile_low",
    close_key: str = "movement_end_close",
) -> Any:
    target_time = _parse_csv_datetime(row.get(timestamp_key))
    if target_time is not None:
        for bar in bars:
            if getattr(bar, "bar_time", None) == target_time:
                return bar

    symbol = row.get("symbol") or (getattr(bars[0], "symbol", "") if bars else "")
    return SimpleNamespace(
        symbol=symbol,
        bar_time=target_time or datetime.datetime.min,
        open_value=safe_float(row.get("movement_start_open"), 0.0) or 0.0,
        high=safe_float(row.get(high_key), None) or safe_float(row.get("movement_high"), 0.0) or 0.0,
        low=safe_float(row.get(low_key), None) or safe_float(row.get("movement_low"), 0.0) or 0.0,
        close=safe_float(row.get(close_key), None) or safe_float(row.get("movement_end_close"), 0.0) or 0.0,
        volume=safe_float(row.get("movement_total_volume"), 0.0) or 0.0,
        volume_average=None,
    )


def _valid_movement_profiles_for_current_bar(
    bars: list[Any],
    current_bar: Any,
) -> list[VolumeProfileContext]:
    cache = _load_valid_movement_profile_cache()
    symbol = str(getattr(current_bar, "symbol", "") or "")
    trade_date = str(current_bar.bar_time.date())
    rows = cache.get((symbol, trade_date), [])
    if not rows:
        return []

    profiles: list[VolumeProfileContext] = []
    for row in rows:
        end_time = _parse_csv_datetime(row.get("movement_end_time"))
        if end_time is None:
            continue
        # The profile must be complete before the entry candidate. Keep the old
        # gap so we do not use a still-forming movement profile.
        if current_bar.bar_time <= end_time + datetime.timedelta(minutes=FRVP_PROFILE_END_GAP_BARS):
            continue

        val = safe_float(row.get("frvp_val"), None)
        poc = safe_float(row.get("frvp_poc"), None)
        vah = safe_float(row.get("frvp_vah"), None)
        fight_zone_high = safe_float(row.get("upper_fight_zone_high"), None)
        profile_high = safe_float(row.get("frvp_profile_high"), None)
        profile_low = safe_float(row.get("frvp_profile_low"), None)
        total_volume = safe_float(row.get("frvp_total_volume"), None)
        if (
            val is None or poc is None or vah is None
            or fight_zone_high is None or profile_high is None or profile_low is None
            or total_volume is None or total_volume <= 0
        ):
            continue

        start_bar = _make_profile_boundary_bar(row, bars, "movement_start_time")
        end_bar = _make_profile_boundary_bar(row, bars, "movement_end_time")
        profile_role = str(row.get("profile_role") or "valid_movement_profile")
        profile_type = f"valid_movement_profile:{profile_role}"

        profiles.append(
            VolumeProfileContext(
                profile_type=profile_type,
                start_bar=start_bar,
                end_bar=end_bar,
                val=round(val, 4),
                poc=round(poc, 4),
                vah=round(vah, 4),
                fight_zone_high=round(max(vah, fight_zone_high), 4),
                profile_high=round(profile_high, 4),
                profile_low=round(profile_low, 4),
                total_volume=round(total_volume, 2),
                volume_by_price={},
                source_metadata=row,
            )
        )

    return profiles


def _candidate_profile_ranges_for_current_bar(
    bars: list[Any],
    current_bar: Any,
) -> list[tuple[str, list[Any]]]:
    same_day_bars = [
        bar for bar in sorted(bars, key=lambda b: b.bar_time)
        if bar.bar_time.date() == current_bar.bar_time.date()
    ]
    current_index = next(
        (index for index, bar in enumerate(same_day_bars) if bar.bar_time == current_bar.bar_time),
        None,
    )
    if current_index is None:
        return []

    cutoff_index = current_index - FRVP_PROFILE_END_GAP_BARS
    if cutoff_index < FRVP_MIN_PROFILE_BARS:
        return []

    prior_bars = same_day_bars[:cutoff_index]
    candidates: list[tuple[str, list[Any]]] = []

    premarket_bars = [bar for bar in prior_bars if bar.bar_time.time() < MARKET_OPEN]
    if len(premarket_bars) >= FRVP_MIN_PROFILE_BARS and current_bar.bar_time.time() >= MARKET_OPEN:
        candidates.append(("premarket_frvp", premarket_bars))

    rth_bars = [bar for bar in prior_bars if MARKET_OPEN <= bar.bar_time.time() <= MARKET_CLOSE]
    if len(rth_bars) >= FRVP_MIN_PROFILE_BARS:
        candidates.append(("rth_from_open_frvp", rth_bars))

    # Rolling completed market profiles catch cases where the first movement is
    # not premarket, or where a later market movement creates the relevant map.
    for window_size in (60, 90, 120, 180, FRVP_MAX_PROFILE_LOOKBACK_BARS):
        if len(prior_bars) >= window_size:
            candidates.append((f"rolling_{window_size}_bar_frvp", prior_bars[-window_size:]))

    # Remove duplicate exact ranges while preserving order.
    unique_candidates: list[tuple[str, list[Any]]] = []
    seen_ranges: set[tuple[Any, Any]] = set()
    for profile_type, profile_bars in candidates:
        if not profile_bars:
            continue
        key = (profile_bars[0].bar_time, profile_bars[-1].bar_time)
        if key in seen_ranges:
            continue
        seen_ranges.add(key)
        unique_candidates.append((profile_type, profile_bars))

    return unique_candidates


def _confirmed_value_breakout_entry_bar_prefilter(current_bar: Any) -> bool:
    close = safe_float(getattr(current_bar, "close", None), None)
    open_value = safe_float(getattr(current_bar, "open_value", None), None)
    high = safe_float(getattr(current_bar, "high", None), None)
    low = safe_float(getattr(current_bar, "low", None), None)
    volume = safe_float(getattr(current_bar, "volume", None), 0.0) or 0.0

    if close is None or open_value is None or high is None or low is None or volume <= 0:
        return False

    candle_range = high - low
    if candle_range <= 0:
        return False

    close_position = (close - low) / candle_range
    upper_wick_share = (high - max(open_value, close)) / candle_range

    return bool(
        close > open_value
        and close_position >= FRVP_MIN_CLOSE_POSITION
        and upper_wick_share <= FRVP_MAX_UPPER_WICK_SHARE
    )


def _volume_confirmation_metrics_for_entry(
    bars: list[Any],
    current_bar: Any,
    avg_lookback_bars: int = FRVP_VOLUME_AVG_LOOKBACK_BARS,
    max_lookback_bars: int = FRVP_VOLUME_MAX_LOOKBACK_BARS,
) -> tuple[Optional[float], Optional[float], Optional[float]]:
    """Return volume expansion metrics used by the profile-aware entry gate.

    Important distinction:
    - Some entries should beat the recent 5-bar max. This is the strict route.
    - Some valid first-clears happen after already-high battle volume. Those
      should not be forced to beat the recent max; they must instead expand
      versus the immediate prior bar and close decisively above the breakout
      line. PAVS 2026-06-09 09:52 is the model case.
    """
    bars_before_current = get_bars_same_day_until(bars, current_bar, include_current=False)
    recent_avg_bars = bars_before_current[-avg_lookback_bars:]
    recent_max_bars = bars_before_current[-max_lookback_bars:]
    previous_bar = bars_before_current[-1] if bars_before_current else None

    recent_avg_volumes = [
        safe_float(getattr(bar, "volume", None), None)
        for bar in recent_avg_bars
    ]
    recent_max_volumes = [
        safe_float(getattr(bar, "volume", None), None)
        for bar in recent_max_bars
    ]
    recent_avg_volumes = [volume for volume in recent_avg_volumes if volume is not None and volume > 0]
    recent_max_volumes = [volume for volume in recent_max_volumes if volume is not None and volume > 0]

    current_volume = safe_float(getattr(current_bar, "volume", None), None)
    previous_volume = safe_float(getattr(previous_bar, "volume", None), None) if previous_bar is not None else None

    if current_volume is None or current_volume <= 0 or not recent_avg_volumes or not recent_max_volumes:
        return (None, None, None)

    recent_avg = sum(recent_avg_volumes) / len(recent_avg_volumes)
    recent_max = max(recent_max_volumes)

    volume_vs_avg = current_volume / recent_avg if recent_avg > 0 else None
    volume_vs_max = current_volume / recent_max if recent_max > 0 else None
    volume_vs_previous = current_volume / previous_volume if previous_volume and previous_volume > 0 else None

    return (volume_vs_avg, volume_vs_max, volume_vs_previous)


def _entry_volume_passes_for_profile(
    current_bar: Any,
    effective_breakout_line: float,
    volume_vs_avg: Optional[float],
    volume_vs_max: Optional[float],
    volume_vs_previous: Optional[float],
) -> bool:
    """Profile-aware volume confirmation.

    Strict path:
        current volume beats both recent average and recent max.

    Decisive-clear path:
        current volume expands versus recent average and the immediate prior bar,
        and the candle closes at least 1% above the actual breakout line. This
        catches first true clears when recent max was already high from battle
        volume, while rejecting barely-over-the-line attempts.
    """
    current_close = safe_float(getattr(current_bar, "close", None), None)
    if current_close is None or effective_breakout_line <= 0:
        return False

    strict_pass = bool(
        volume_vs_avg is not None
        and volume_vs_max is not None
        and volume_vs_avg >= FRVP_MIN_VOLUME_EXPANSION_VS_AVG
        and volume_vs_max >= FRVP_MIN_VOLUME_EXPANSION_VS_MAX
    )

    decisive_clear_pass = bool(
        volume_vs_avg is not None
        and volume_vs_previous is not None
        and volume_vs_avg >= FRVP_MIN_DECISIVE_VOLUME_EXPANSION_VS_AVG
        and volume_vs_previous >= FRVP_MIN_DECISIVE_VOLUME_EXPANSION_VS_PREVIOUS
        and current_close >= effective_breakout_line * (1 + FRVP_MIN_DECISIVE_CLOSE_ABOVE_LINE_PCT)
    )

    return strict_pass or decisive_clear_pass


def _setup_low_bar_between_profile_and_entry(
    profile: VolumeProfileContext,
    bars: list[Any],
    current_bar: Any,
) -> Any:
    candidates = [
        bar for bar in bars
        if (
            bar.bar_time.date() == current_bar.bar_time.date()
            and profile.end_bar.bar_time < bar.bar_time <= current_bar.bar_time
        )
    ]
    if not candidates:
        candidates = [current_bar]

    return sorted(
        candidates,
        key=lambda bar: (
            safe_float(getattr(bar, "low", None), math.inf),
            getattr(bar, "bar_time", datetime.datetime.max),
        ),
    )[0]



def _profile_effective_breakout_line(profile: VolumeProfileContext) -> float:
    """Return the line that price must truly clear for this profile.

    v4: do not automatically require the absolute profile high. In the AKAN
    2026-04-29 style cases, a profile can contain an old/wicky high above the
    true seller-fight shelf. Requiring that absolute high made the detector wait
    too late. The real rule is VAH + meaningful fight-zone shelf clearance.
    Prior rejection highs are handled separately by the fresh-reclaim/volume
    behavior instead of being baked into every profile line.
    """
    return max(profile.vah, profile.fight_zone_high)


def _recently_reclaimed_breakout_line(
    bars: list[Any],
    current_bar: Any,
    breakout_line: float,
    lookback_bars: int = FRVP_RECLAIM_LOOKBACK_BARS,
) -> bool:
    """Fresh-reclaim gate: avoid late duplicate volume pops above the same line."""
    if breakout_line <= 0:
        return False

    bars_before_current = get_bars_same_day_until(bars, current_bar, include_current=False)
    recent_bars = bars_before_current[-lookback_bars:]
    if not recent_bars:
        return False

    tolerance_line = breakout_line * (1 + FRVP_LEVEL_TOLERANCE_PCT)
    for bar in recent_bars:
        close = safe_float(getattr(bar, "close", None), None)
        low = safe_float(getattr(bar, "low", None), None)
        if close is not None and close <= tolerance_line:
            return True
        if low is not None and low <= tolerance_line:
            return True

    return False


def _blocks_weaker_adaptive_profile(
    current_bar: Any,
    current_profile: VolumeProfileContext,
    all_profiles: list[VolumeProfileContext],
) -> bool:
    """Block easier profiles while a harder prior map is still unresolved.

    v3 tightening:
    - v2 only blocked rolling profiles against harder premarket/RTH maps.
    - That was still too loose: early RTH profiles could fire while the
      premarket VAH/fight-zone/profile-high was still overhead.
    - Now any non-primary/easier profile is blocked if an older primary map has
      a meaningfully higher effective breakout line that the current close has
      not cleared.
    """
    current_close = safe_float(getattr(current_bar, "close", None), None)
    if current_close is None or current_close <= 0:
        return True

    current_line = _profile_effective_breakout_line(current_profile)

    for profile in all_profiles:
        if profile is current_profile:
            continue

        # Premarket is the broadest prior map for regular-session entries.
        # Do not allow an easier RTH/rolling profile to trigger while that
        # premarket war-zone/high is still above price.
        if (
            profile.profile_type == "premarket_frvp"
            and current_profile.profile_type != "premarket_frvp"
        ):
            hard_line = _profile_effective_breakout_line(profile)
            if (
                hard_line > current_line * 1.01
                and current_close <= hard_line * (1 + FRVP_LEVEL_TOLERANCE_PCT)
            ):
                return True

        # RTH-from-open is harder than rolling profiles. Keep the v2 protection
        # so rolling windows cannot adapt the breakout line downward too easily.
        if (
            profile.profile_type == "rth_from_open_frvp"
            and current_profile.profile_type.startswith("rolling_")
        ):
            hard_line = _profile_effective_breakout_line(profile)
            if (
                hard_line > current_line * 1.01
                and current_close <= hard_line * (1 + FRVP_LEVEL_TOLERANCE_PCT)
            ):
                return True

    return False


def _rank_confirmed_value_context(context: BreakoutContext) -> tuple[float, float, float]:
    """Prefer the hardest meaningful fight line and strongest relative volume."""
    helper_context = context.helper_context or {}
    vah = safe_float(helper_context.get("frvp_vah"), 0.0) or 0.0
    fight_zone_high = safe_float(helper_context.get("frvp_fight_zone_high"), 0.0) or 0.0
    volume_vs_max = safe_float(helper_context.get("frvp_entry_volume_vs_recent_max"), 0.0) or 0.0
    close = safe_float(getattr(context.entry_bar, "close", None), 0.0) or 0.0
    return (max(vah, fight_zone_high), volume_vs_max, close)

def _build_confirmed_value_breakout_context(
    current_bar: Any,
    bars: list[Any],
    profile: VolumeProfileContext,
    volume_vs_avg: Optional[float],
    volume_vs_max: Optional[float],
    volume_vs_previous: Optional[float],
) -> Optional[BreakoutContext]:
    current_close = safe_float(getattr(current_bar, "close", None), None)
    if current_close is None or current_close <= 0:
        return None

    effective_breakout_line = _profile_effective_breakout_line(profile)

    if current_close <= effective_breakout_line * (1 + FRVP_LEVEL_TOLERANCE_PCT):
        return None

    if not _entry_volume_passes_for_profile(
        current_bar=current_bar,
        effective_breakout_line=effective_breakout_line,
        volume_vs_avg=volume_vs_avg,
        volume_vs_max=volume_vs_max,
        volume_vs_previous=volume_vs_previous,
    ):
        return None

    if not _recently_reclaimed_breakout_line(
        bars=bars,
        current_bar=current_bar,
        breakout_line=effective_breakout_line,
    ):
        return None

    support_low_bar = _setup_low_bar_between_profile_and_entry(profile, bars, current_bar)

    helper_context = {
        "reason": "confirmed_value_breakout_frvp",
        "case_type": "confirmed_value_breakout_frvp",
        "resistance_bar": profile.end_bar,
        "support_bar": support_low_bar,
        "breakout_bar": current_bar,
        "resistance_price": effective_breakout_line,
        "breakout_close": current_close,
        "frvp_profile_type": profile.profile_type,
        "frvp_profile_start_bar": profile.start_bar,
        "frvp_profile_end_bar": profile.end_bar,
        "frvp_val": profile.val,
        "frvp_poc": profile.poc,
        "frvp_vah": profile.vah,
        "frvp_fight_zone_high": profile.fight_zone_high,
        "frvp_profile_high": profile.profile_high,
        "frvp_profile_low": profile.profile_low,
        "frvp_total_volume": profile.total_volume,
        "frvp_profile_role": (profile.source_metadata or {}).get("profile_role"),
        "frvp_session_type": (profile.source_metadata or {}).get("session_type"),
        "frvp_movement_type": (profile.source_metadata or {}).get("movement_type"),
        "frvp_movement_quality_score": (profile.source_metadata or {}).get("movement_quality_score"),
        "frvp_movement_is_valid": str((profile.source_metadata or {}).get("movement_is_valid", "")).lower() in {"true", "1", "yes", "y"},
        "frvp_movement_invalid_reasons": (profile.source_metadata or {}).get("movement_invalid_reasons"),
        "frvp_entry_close_above_vah": current_close > profile.vah,
        "frvp_entry_close_above_fight_zone": current_close > profile.fight_zone_high,
        "frvp_entry_volume_confirmation": True,
        "frvp_entry_volume_vs_recent_avg": volume_vs_avg,
        "frvp_entry_volume_vs_recent_max": volume_vs_max,
        "frvp_entry_volume_vs_previous_bar": volume_vs_previous,
    }

    context = _build_context_from_helper_context(
        current_bar=current_bar,
        bars=bars,
        matched_family="confirmed_value_breakout_frvp",
        helper_context=helper_context,
    )
    if context is None:
        return None

    context.breakout_type = "confirmed_value_breakout_frvp"
    context.case_type = "confirmed_value_breakout_frvp"
    context.reason = "confirmed_value_breakout_frvp"
    return context


def find_confirmed_value_breakout_contexts(
    current_bar: Any,
    bars: list[Any],
    one_minute_timeframe_stock: common.objects.Stock,
    helper: Any = None,
) -> list[BreakoutContext]:
    """Detect Confirmed Value Breakout using validated movement profiles.

    The FRVP range is no longer guessed inside this breakout finder when
    FRVP_USE_VALID_MOVEMENT_PROFILE_FILE=True. It is loaded from
    model/frvp_movement_profiles_valid.csv, which was generated by the movement
    profile finder and already passed the movement/no-movement gate.

    Rule being tested:
      current bar closes above previous profile VAH
      AND closes above the hidden seller-fight zone above VAH, if one exists
      AND has clear volume expansion versus preceding bars.
    """
    del one_minute_timeframe_stock, helper

    if current_bar.bar_time.time() < MARKET_OPEN:
        return []

    if not _confirmed_value_breakout_entry_bar_prefilter(current_bar):
        return []

    volume_vs_avg, volume_vs_max, volume_vs_previous = _volume_confirmation_metrics_for_entry(
        bars=bars,
        current_bar=current_bar,
    )
    if volume_vs_avg is None or volume_vs_max is None:
        return []

    if FRVP_USE_VALID_MOVEMENT_PROFILE_FILE:
        profiles = _valid_movement_profiles_for_current_bar(bars, current_bar)
    else:
        profiles: list[VolumeProfileContext] = []
        for profile_type, profile_bars in _candidate_profile_ranges_for_current_bar(bars, current_bar):
            profile = _calculate_volume_profile(profile_bars)
            if profile is None:
                continue
            profile.profile_type = profile_type
            profiles.append(profile)

    contexts: list[BreakoutContext] = []
    for profile in profiles:
        if (
            not FRVP_USE_VALID_MOVEMENT_PROFILE_FILE
            and _blocks_weaker_adaptive_profile(
                current_bar=current_bar,
                current_profile=profile,
                all_profiles=profiles,
            )
        ):
            continue

        context = _build_confirmed_value_breakout_context(
            current_bar=current_bar,
            bars=bars,
            profile=profile,
            volume_vs_avg=volume_vs_avg,
            volume_vs_max=volume_vs_max,
            volume_vs_previous=volume_vs_previous,
        )
        if context is not None:
            contexts.append(context)

    if not contexts:
        return []

    # Only export the strongest profile for this bar. Multiple FRVP windows can
    # describe the same breakout, and exporting all of them caused duplicates.
    return [sorted(contexts, key=_rank_confirmed_value_context, reverse=True)[0]]


def find_behavioral_buyer_control_phase_20pct_30min_entry_contexts(
    current_bar: Any,
    bars: list[Any],
    one_minute_timeframe_stock: common.objects.Stock,
    helper: Any = None,
) -> list[BreakoutContext]:
    """Return one BreakoutContext per CaseDetails from helper.

    Current helper contract only:
        Helper.bar_potential_case_details(...) returns a list containing:
        - ClassicCaseDetails
        - OneSupportToManyResistanceCaseDetails
        - ManySupportsToOneResistanceCaseDetails

    The group CaseDetails objects may contain many support/resistance bars.
    The finder chooses one representative support/resistance for the existing
    single-column export, while preserving the full bar groups in helper_context.
    """
    if not _entry_bar_prefilter_passes(current_bar):
        return []

    if helper is None:
        if PatternDetectorExecutor is not None:
            helper = PatternDetectorExecutor()
        else:
            helper = buying_confirmator.helper.Helper()

    if hasattr(helper, "find_support_to_resistance_patterns"):
        case_details_list = helper.find_support_to_resistance_patterns(
            one_minute_timeframe_stock=one_minute_timeframe_stock,
            potential_confirmation_bar=current_bar,
        )
    elif hasattr(helper, "bar_potential_case_details"):
        case_details_list = helper.bar_potential_case_details(
            one_minute_timeframe_stock=one_minute_timeframe_stock,
            potential_confirmation_bar=current_bar,
        )
    else:
        raise AttributeError(
            "Pattern executor must define find_support_to_resistance_patterns(...) "
            "or legacy Helper must define bar_potential_case_details(...)."
        )

    if case_details_list is None:
        return []

    if not isinstance(case_details_list, list):
        raise TypeError(
            "Helper.bar_potential_case_details(...) must return a list of CaseDetails-like objects. "
            f"Got {type(case_details_list).__name__}."
        )

    contexts: list[BreakoutContext] = []
    for case_details in case_details_list:
        if case_details is None:
            continue

        # helper(37) classes no longer expose is_positive. If the attribute is
        # present and explicitly False, skip; otherwise treat returned cases as
        # positive because the helper already filtered them.
        if getattr(case_details, "is_positive", True) is False:
            continue

        case_type = _case_type_from_case_details(case_details)
        case_support_bar = _choose_support_bar_for_case_details(case_details)
        case_resistance_bar = _choose_resistance_bar_for_case_details(
            case_details=case_details,
            support_bar=case_support_bar,
        )
        case_breakout_bar = getattr(case_details, "breakout_bar", None)

        if case_support_bar is None:
            raise AttributeError(
                "CaseDetails must expose support_bar or non-empty support_bars."
            )

        if case_resistance_bar is None:
            raise AttributeError(
                "CaseDetails must expose resistance_bar or non-empty resistance_bars."
            )

        matched_family = case_type or "bar_potential_case_details"

        helper_context_from_case_details = {
            "reason": matched_family,
            "case_type": case_type,
            "resistance_bar": case_resistance_bar,
            "support_bar": case_support_bar,
            "breakout_bar": case_breakout_bar,
            "resistance_price": safe_float(getattr(case_resistance_bar, "high", None), None),
        }
        helper_context_from_case_details.update(
            _case_details_group_metadata(case_details)
        )

        context = _build_context_from_helper_context(
            current_bar=current_bar,
            bars=bars,
            matched_family=matched_family,
            helper_context=helper_context_from_case_details,
        )
        if context is not None:
            contexts.append(context)

    return contexts


def find_breakout_contexts(
    current_bar: Any,
    bars: list[Any],
    one_minute_timeframe_stock: common.objects.Stock,
    helper: Any = None,
) -> list[BreakoutContext]:
    """Live/export decision for the new Confirmed Value Breakout pattern."""
